package com.leon.workflow.messaging;

import jakarta.annotation.PostConstruct;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.http.HttpStatus;
import tools.jackson.databind.ObjectMapper;
import java.util.*;

/** Account-owned snapshots. Images remain private and survive clearing the source chat. */
@Service
public class ChatFavorites {
    public record Item(long id,DeviceMessageStore.Message message,String conversationName,long savedAt) {}
    public record Page(List<Item> results,boolean hasMore,Long nextBefore) {}
    private final JdbcTemplate jdbc;private final DeviceMessageStore store;private final ChatAccess access;private final ObjectMapper json;
    public ChatFavorites(JdbcTemplate jdbc,DeviceMessageStore store,ChatAccess access,ObjectMapper json){this.jdbc=jdbc;this.store=store;this.access=access;this.json=json;}
    @PostConstruct void initialize(){
        jdbc.execute("CREATE TABLE IF NOT EXISTS chat_favorite (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id VARCHAR(36) NOT NULL,source_message_id BIGINT NOT NULL,conversation_name VARCHAR(60) NOT NULL,sender VARCHAR(60) NOT NULL,body VARCHAR(8000) NOT NULL,snapshot_json CLOB NOT NULL,saved_at BIGINT NOT NULL,CONSTRAINT uq_chat_favorite UNIQUE(user_id,source_message_id))");
        jdbc.execute("CREATE INDEX IF NOT EXISTS idx_chat_favorite_user ON chat_favorite(user_id,id)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS chat_favorite_image (favorite_id BIGINT NOT NULL,image_id VARCHAR(36) NOT NULL,image_data BLOB NOT NULL,PRIMARY KEY(favorite_id,image_id))");
        jdbc.execute("CREATE TABLE IF NOT EXISTS chat_favorite_document(favorite_id BIGINT NOT NULL,document_id VARCHAR(36) NOT NULL,name VARCHAR(180) NOT NULL,document_data BLOB NOT NULL,PRIMARY KEY(favorite_id,document_id))");
    }
    public Item add(ChatUserRegistry.User user,long messageId){
        if(messageId<=0)throw DeviceMessageStore.bad("消息标识无效");
        synchronized(store){
            var old=jdbc.queryForList("SELECT id FROM chat_favorite WHERE user_id=? AND source_message_id=?",Long.class,user.id(),messageId);
            if(!old.isEmpty())return item(user.id(),old.getFirst());
            var message=store.message(messageId);access.require(user,message.conversationId(),false);
            String snapshot=json.writeValueAsString(message),name=store.conversation(message.conversationId()).name();
            return store.atomic(()->{
                jdbc.update("INSERT INTO chat_favorite(user_id,source_message_id,conversation_name,sender,body,snapshot_json,saved_at) VALUES(?,?,?,?,?,?,?)",user.id(),messageId,name,message.sender(),message.text(),snapshot,System.currentTimeMillis());
                long id=jdbc.queryForObject("SELECT id FROM chat_favorite WHERE user_id=? AND source_message_id=?",Long.class,user.id(),messageId);
                for(var image:message.images()){
                    int count=jdbc.update("INSERT INTO chat_favorite_image(favorite_id,image_id,image_data) SELECT ?,id,image_data FROM chat_message_image WHERE id=? AND conversation_id=?",id,image.id(),message.conversationId());
                    if(count!=1)throw DeviceMessageStore.bad("原图片已不可用，请重新加载后收藏");
                }
                for(var doc:message.documents()){
                    int count=jdbc.update("INSERT INTO chat_favorite_document(favorite_id,document_id,name,document_data) SELECT ?,id,name,document_data FROM chat_message_document WHERE id=? AND conversation_id=?",id,doc.id(),message.conversationId());
                    if(count!=1)throw DeviceMessageStore.bad("原附件已不可用，请重新加载后收藏");
                }
                return item(user.id(),id);
            });
        }
    }
    private Item item(String user,long id){
        var rows=jdbc.query("SELECT * FROM chat_favorite WHERE user_id=? AND id=?",(rs,n)->new Item(rs.getLong("id"),json.readValue(rs.getString("snapshot_json"),DeviceMessageStore.Message.class),rs.getString("conversation_name"),rs.getLong("saved_at")),user,id);
        if(rows.isEmpty())throw missing();return rows.getFirst();
    }
    public Page page(String user,String query,Long before,int limit){
        String q=query==null?"":query.strip();
        if(q.length()>100||q.codePoints().anyMatch(Character::isISOControl)||before!=null&&before<=0||limit<1||limit>50)throw DeviceMessageStore.bad("收藏搜索或分页参数无效");
        String sql="SELECT id FROM chat_favorite WHERE user_id=? AND (LOCATE(LOWER(?),LOWER(body))>0 OR LOCATE(LOWER(?),LOWER(sender))>0 OR LOCATE(LOWER(?),LOWER(conversation_name))>0 OR EXISTS(SELECT 1 FROM chat_favorite_document d WHERE d.favorite_id=chat_favorite.id AND LOCATE(LOWER(?),LOWER(d.name))>0))";
        var args=new ArrayList<Object>(List.of(user,q,q,q,q));if(before!=null){sql+=" AND id<?";args.add(before);}sql+=" ORDER BY id DESC LIMIT ?";args.add(limit+1);
        synchronized(store){
            var ids=jdbc.queryForList(sql,Long.class,args.toArray());boolean more=ids.size()>limit;
            var selected=ids.subList(0,Math.min(limit,ids.size()));var result=selected.stream().map(id->item(user,id)).toList();
            return new Page(result,more,more?selected.getLast():null);
        }
    }
    public void remove(String user,long id){
        synchronized(store){store.atomic(()->{
            jdbc.update("DELETE FROM chat_favorite_document WHERE favorite_id=? AND EXISTS(SELECT 1 FROM chat_favorite WHERE id=? AND user_id=?)",id,id,user);
            jdbc.update("DELETE FROM chat_favorite_image WHERE favorite_id=? AND EXISTS(SELECT 1 FROM chat_favorite WHERE id=? AND user_id=?)",id,id,user);
            jdbc.update("DELETE FROM chat_favorite WHERE id=? AND user_id=?",id,user);return true;
        });}
    }
    public byte[] document(String user,long id,String document){
        document=DeviceMessageStore.uuid(document);
        synchronized(store){var rows=jdbc.query("SELECT d.document_data FROM chat_favorite_document d JOIN chat_favorite f ON f.id=d.favorite_id WHERE f.user_id=? AND f.id=? AND d.document_id=?",(rs,n)->rs.getBytes(1),user,id,document);
            if(rows.isEmpty())throw missing();return rows.getFirst();}
    }
    public byte[] image(String user,long id,String image){
        image=DeviceMessageStore.uuid(image);
        synchronized(store){
            var rows=jdbc.query("SELECT i.image_data FROM chat_favorite_image i JOIN chat_favorite f ON f.id=i.favorite_id WHERE f.user_id=? AND f.id=? AND i.image_id=?",(rs,n)->rs.getBytes(1),user,id,image);
            if(rows.isEmpty())throw missing();return rows.getFirst();
        }
    }
    private static org.springframework.web.server.ResponseStatusException missing(){return DeviceMessageStore.failure(HttpStatus.NOT_FOUND,"收藏不存在或无权访问");}
}
