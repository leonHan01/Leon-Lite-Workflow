package com.leon.workflow.messaging;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.nio.file.Path;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class DeviceMessagePersistenceTest {
    @TempDir Path temporary;
    @Test void messagesAndRetryKeysSurviveDatabaseCloseAndReopen() {
        String url = "jdbc:h2:file:" + temporary.resolve("messages");
        var first = new JdbcTemplate(new DriverManagerDataSource(url, "sa", ""));
        var original = new DeviceMessageStore(first); original.initialize();
        var input = new DeviceMessageStore.Send(UUID.randomUUID().toString(), UUID.randomUUID().toString(), "Android", "android", "保留到重启以后");
        var saved = original.send(input);
        first.execute("SHUTDOWN");
        var reopened = new JdbcTemplate(new DriverManagerDataSource(url, "sa", ""));
        var restarted = new DeviceMessageStore(reopened); restarted.initialize();
        assertEquals(saved, restarted.page(null, null, 100).messages().getFirst());
        assertEquals(saved, restarted.send(input));
        assertEquals(1, restarted.page(0L, null, 100).messages().size());
        reopened.execute("SHUTDOWN");
    }
    @Test void upgradesLegacyMessageTableWithoutChangingIdsOrContents() {
        String url = "jdbc:h2:file:" + temporary.resolve("legacy");
        var jdbc = new JdbcTemplate(new DriverManagerDataSource(url, "sa", ""));
        jdbc.execute("CREATE TABLE device_message(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,client_message_id VARCHAR(36) NOT NULL,device_id VARCHAR(36) NOT NULL,sender VARCHAR(60) NOT NULL,platform VARCHAR(16) NOT NULL,body VARCHAR(8000) NOT NULL,created_at BIGINT NOT NULL,CONSTRAINT uq_device_message_retry UNIQUE(device_id,client_message_id))");
        jdbc.update("INSERT INTO device_message(id,client_message_id,device_id,sender,platform,body,created_at) VALUES(42,?,?,?,'macos',?,1)",UUID.randomUUID().toString(),UUID.randomUUID().toString(),"旧设备","原始消息");
        var upgraded = new DeviceMessageStore(jdbc);upgraded.initialize();upgraded.initialize();
        var message = upgraded.page(null,null,100).messages().getFirst();
        assertEquals(42,message.id());assertEquals("原始消息",message.text());assertEquals("shared",message.conversationId());assertEquals("user",message.role());
        jdbc.execute("SHUTDOWN");
    }
}
