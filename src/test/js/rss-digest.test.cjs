const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../../../scripts/workflows/rss_digest_format.js'), 'utf8'), context);
const format = input => JSON.parse(JSON.stringify(context.main(input, {})));
const article = (id, summary) => ({title: '文章 ' + id, source: '测试源', url: 'https://example.com/' + id, summary});
const report = articles => ({items: [{json: {title: '科技日报', summary: '本批重点是架构与 AI 更新。', articles, warnings: []}}]});
const articles = Array.from({length:31}, (_, i) => article(i + 1, i >= 21 ? '【精选' + String(31 - i).padStart(2,'0') + '】值得精读的技术变化及其实际价值。' : '【速览】这是一条简短介绍。'));
const output = format(report(articles)).items[0].json;
assert.equal(output.selectedCount, 10); assert.equal(output.briefCount, 21); assert.equal(output.articleCount, 31);
assert.equal(output.articles[0].url, 'https://example.com/31', '必须按模型评选的阅读价值排序，而非截取输入前10篇');
assert.equal(new Set(output.articles.map(a => a.url)).size, 31, '速览不能丢失其余文章');
assert.ok(output.feishuMarkdown.includes('最值得看的 10 篇')); assert.ok(output.feishuMarkdown.includes('其余速览（21 篇）'));
assert.ok(!output.feishuMarkdown.includes('【精选')); assert.ok(!output.emailBody.includes('【速览】'));
assert.ok(Buffer.byteLength(JSON.stringify(output.feishuMarkdown)) < 16000);
const short = format(report([article(1,'【精选01】第一篇的价值。'),article(2,'【精选02】第二篇的价值。')]));
assert.equal(short.items[0].json.selectedCount,2); assert.equal(short.items[0].json.briefCount,0);
assert.deepEqual(format({items:[]}), {items:[]});
assert.throws(() => format(report(articles.map((a,i) => i === 30 ? {...a,summary:'【精选02】重复序号'} : a))), /重复/);
assert.throws(() => format(report(articles.map((a,i) => i === 30 ? {...a,summary:'【速览】未选满'} : a))), /需要评选/);
assert.throws(() => format(report([article(1,'没有格式标记')])) , /格式/);
const unsafe = format(report([{...article(1,'【精选01】<script>alert(1)</script>'),title:'<img src=x>',url:'javascript:alert(1)'}])).items[0].json;
assert.ok(!unsafe.emailHtml.includes('<script>')); assert.ok(!unsafe.emailHtml.includes('<img')); assert.ok(!unsafe.feishuMarkdown.includes('javascript:'));
console.log('RSS digest formatter passed: ranked top10, concise remaining articles, empty/small batches, source preservation, invalid rankings and escaped output.');
